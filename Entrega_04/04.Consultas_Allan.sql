SELECT ANO, GRP_NOME, COUNT(DISTINCT COT_PAP_ID) AS APRESENTACOES,
       SUM(QTD_COTACOES) AS COTACOES
FROM MV_PRECOS_ANUAIS
GROUP BY ANO, GRP_NOME
ORDER BY ANO, COTACOES DESC;

SELECT ANO, PRD_NOME, PRD_VAR, COT_PAP_ID,
       PAP_QTD, TIPO_APRESENTACAO, UMD_SIGLA,
       QTD_COM_PRECO_MEDIO, PRECO_MEDIO_ANO
FROM MV_PRECOS_ANUAIS
WHERE QTD_COM_PRECO_MEDIO > 0
ORDER BY ANO DESC, PRD_NOME;

SELECT PRD_NOME, PRD_VAR, COT_PAP_ID, PAP_QTD,
       TIPO_APRESENTACAO, UMD_SIGLA,
       ROUND(AVG(ABS(VARIACAO_PERCENTUAL)), 2) AS OSCILACAO_MEDIA_PCT,
       COUNT(*) AS INTERVALOS_AVALIADOS
FROM VW_VARIACAO_BOLETINS
WHERE VARIACAO_PERCENTUAL IS NOT NULL
GROUP BY PRD_NOME, PRD_VAR, COT_PAP_ID,
         PAP_QTD, TIPO_APRESENTACAO, UMD_SIGLA
HAVING COUNT(*) >= 3
ORDER BY OSCILACAO_MEDIA_PCT DESC;

SELECT PRD_NOME, PRD_VAR, COT_PAP_ID,
       PAP_QTD, TIPO_APRESENTACAO, UMD_SIGLA,
       ROUND(AVG(AMPLITUDE_PERCENTUAL), 2) AS DISPERSAO_MEDIA_PCT,
       COUNT(*) AS COTACOES_AVALIADAS
FROM VW_DISPERSAO_PRECOS
WHERE AMPLITUDE_PERCENTUAL IS NOT NULL
GROUP BY PRD_NOME, PRD_VAR, COT_PAP_ID,
         PAP_QTD, TIPO_APRESENTACAO, UMD_SIGLA
HAVING COUNT(*) >= 3
ORDER BY DISPERSAO_MEDIA_PCT DESC;

SELECT PRD_NOME, PRD_VAR, COT_PAP_ID,
       PAP_QTD, TIPO_APRESENTACAO, UMD_SIGLA,
       COUNT(DISTINCT EXTRACT(YEAR FROM BLT_DATA_LEV)) AS ANOS_COM_COTACAO,
       MIN(BLT_DATA_LEV) AS PRIMEIRA_COTACAO,
       MAX(BLT_DATA_LEV) AS ULTIMA_COTACAO,
       COUNT(*) AS TOTAL_COTACOES
FROM VW_COTACOES_DETALHADAS
GROUP BY PRD_NOME, PRD_VAR, COT_PAP_ID,
         PAP_QTD, TIPO_APRESENTACAO, UMD_SIGLA
ORDER BY ANOS_COM_COTACAO DESC, TOTAL_COTACOES DESC;

SELECT PRD_NOME, PRD_VAR, COT_PAP_ID,
       PAP_QTD, TIPO_APRESENTACAO, UMD_SIGLA,
       MES_LEVANTAMENTO, PRECO_MEDIO_MES,
       ROUND(PRECO_MEDIO_MES - LAG(PRECO_MEDIO_MES) OVER (
           PARTITION BY COT_PAP_ID ORDER BY MES_LEVANTAMENTO
       ), 2) AS VARIACAO_MENSAL_REAIS,
       CASE WHEN LAG(PRECO_MEDIO_MES) OVER (
           PARTITION BY COT_PAP_ID ORDER BY MES_LEVANTAMENTO
       ) > 0 THEN ROUND(100 * (
           PRECO_MEDIO_MES / LAG(PRECO_MEDIO_MES) OVER (
               PARTITION BY COT_PAP_ID ORDER BY MES_LEVANTAMENTO
           ) - 1
       ), 2) END AS VARIACAO_MENSAL_PCT
FROM MV_PRECOS_MENSAIS
WHERE PRECO_MEDIO_MES IS NOT NULL
ORDER BY PRD_NOME, COT_PAP_ID, MES_LEVANTAMENTO;

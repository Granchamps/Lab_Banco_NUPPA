CREATE OR REPLACE VIEW VW_COTACOES_UNIFICADAS AS
SELECT COT_ID, COT_BLT_ID, COT_PAP_ID,
       COT_PRC_COMUM, COT_PRC_MIN, COT_PRC_MAX,
       COT_PRC_MED, COT_PRC_MEDIANA, 'ATUAL' AS ORIGEM
FROM NUPPA.COTACAO
UNION ALL
SELECT HCOT_ID, HCOT_BLT_ID, HCOT_PAP_ID,
       HCOT_PRC_COMUM, HCOT_PRC_MIN, HCOT_PRC_MAX,
       HCOT_PRC_MED, HCOT_PRC_MEDIANA, 'HISTORICO' AS ORIGEM
FROM (
    SELECT H.*,
           ROW_NUMBER() OVER (
               PARTITION BY HCOT_BLT_ID, HCOT_PAP_ID
               ORDER BY HCOT_DT_ENTRADA DESC, HCOT_ID DESC
           ) AS RN
    FROM NUPPA.H_COTACAO H
) H
WHERE RN = 1
  AND NOT EXISTS (
      SELECT 1
      FROM NUPPA.COTACAO C
      WHERE C.COT_BLT_ID = H.HCOT_BLT_ID
        AND C.COT_PAP_ID = H.HCOT_PAP_ID
  );

CREATE OR REPLACE VIEW VW_COTACOES_DETALHADAS AS
SELECT C.COT_ID, C.COT_BLT_ID, C.COT_PAP_ID, C.ORIGEM,
       B.BLT_NUM, B.BLT_ANO, B.BLT_DATA_LEV,
       TRUNC(B.BLT_DATA_LEV, 'MM') AS MES_LEVANTAMENTO,
       P.PRD_ID, P.PRD_NOME, P.PRD_VAR,
       CA.CAT_ID, CA.CAT_NOME, G.GRP_ID, G.GRP_NOME,
       PA.PAP_QTD, TA.TAP_NOME AS TIPO_APRESENTACAO,
       UM.UMD_NOME, UM.UMD_SIGLA,
       C.COT_PRC_COMUM, C.COT_PRC_MIN, C.COT_PRC_MAX,
       C.COT_PRC_MED, C.COT_PRC_MEDIANA,
       C.COT_PRC_MAX - C.COT_PRC_MIN AS AMPLITUDE_PRECO
FROM VW_COTACOES_UNIFICADAS C
JOIN NUPPA.BOLETIM B ON B.BLT_ID = C.COT_BLT_ID
JOIN NUPPA.PRODUTO_APRESENTACAO PA ON PA.PAP_ID = C.COT_PAP_ID
JOIN NUPPA.PRODUTO P ON P.PRD_ID = PA.PAP_PRD_ID
JOIN NUPPA.CATEGORIA CA ON CA.CAT_ID = P.PRD_CAT_ID
JOIN NUPPA.GRUPO_ALIMENTAR G ON G.GRP_ID = CA.CAT_GRP_ID
JOIN NUPPA.TIPO_APRESENTACAO TA ON TA.TAP_ID = PA.PAP_TAP_ID
LEFT JOIN NUPPA.UNIDADE_MEDIDA UM ON UM.UMD_ID = PA.PAP_UMD_ID;

CREATE OR REPLACE VIEW VW_PRECOS_MENSAIS AS
SELECT MES_LEVANTAMENTO, COT_PAP_ID, PRD_ID, PRD_NOME, PRD_VAR,
       CAT_NOME, GRP_NOME, PAP_QTD, TIPO_APRESENTACAO, UMD_SIGLA,
       COUNT(*) AS QTD_COTACOES,
       COUNT(COT_PRC_MED) AS QTD_COM_PRECO_MEDIO,
       ROUND(AVG(COT_PRC_MED), 2) AS PRECO_MEDIO_MES,
       MIN(COT_PRC_MIN) AS MENOR_PRECO_MES,
       MAX(COT_PRC_MAX) AS MAIOR_PRECO_MES
FROM VW_COTACOES_DETALHADAS
GROUP BY MES_LEVANTAMENTO, COT_PAP_ID, PRD_ID, PRD_NOME, PRD_VAR,
         CAT_NOME, GRP_NOME, PAP_QTD, TIPO_APRESENTACAO, UMD_SIGLA;

CREATE OR REPLACE VIEW VW_VARIACAO_BOLETINS AS
SELECT X.*,
       ROUND(COT_PRC_MED - PRECO_ANTERIOR, 2) AS VARIACAO_REAIS,
       CASE WHEN PRECO_ANTERIOR > 0 THEN
           ROUND(100 * (COT_PRC_MED - PRECO_ANTERIOR) / PRECO_ANTERIOR, 2)
       END AS VARIACAO_PERCENTUAL
FROM (
    SELECT COT_PAP_ID, PRD_NOME, PRD_VAR, PAP_QTD,
           TIPO_APRESENTACAO, UMD_SIGLA, BLT_NUM, BLT_ANO,
           BLT_DATA_LEV, COT_PRC_MED,
           LAG(COT_PRC_MED) OVER (
               PARTITION BY COT_PAP_ID
               ORDER BY BLT_DATA_LEV, COT_BLT_ID
           ) AS PRECO_ANTERIOR
    FROM VW_COTACOES_DETALHADAS
) X;

CREATE OR REPLACE VIEW VW_DISPERSAO_PRECOS AS
SELECT BLT_DATA_LEV, BLT_NUM, BLT_ANO, COT_PAP_ID,
       PRD_NOME, PRD_VAR, CAT_NOME, PAP_QTD,
       TIPO_APRESENTACAO, UMD_SIGLA,
       COT_PRC_MIN, COT_PRC_MAX, COT_PRC_MED, AMPLITUDE_PRECO,
       CASE WHEN COT_PRC_MIN > 0 THEN
           ROUND(100 * AMPLITUDE_PRECO / COT_PRC_MIN, 2)
       END AS AMPLITUDE_PERCENTUAL
FROM VW_COTACOES_DETALHADAS;

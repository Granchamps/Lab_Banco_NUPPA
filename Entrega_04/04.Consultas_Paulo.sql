SELECT BLT_ANO, COUNT(DISTINCT COT_BLT_ID) AS BOLETINS,
       COUNT(*) AS COTACOES,
       COUNT(COT_PRC_MED) AS COTACOES_COM_PRECO_MEDIO
FROM VW_COTACOES_DETALHADAS
GROUP BY BLT_ANO
ORDER BY BLT_ANO;

SELECT BLT_DATA_LEV, BLT_ANO, BLT_NUM,
       COUNT(*) AS PRODUTOS_COTADOS,
       COUNT(COT_PRC_MED) AS PRODUTOS_COM_PRECO_MEDIO
FROM VW_COTACOES_DETALHADAS
GROUP BY BLT_DATA_LEV, BLT_ANO, BLT_NUM
ORDER BY BLT_DATA_LEV DESC;

SELECT CAT_NOME, COUNT(DISTINCT COT_PAP_ID) AS APRESENTACOES,
       COUNT(*) AS COTACOES
FROM VW_COTACOES_DETALHADAS
GROUP BY CAT_NOME
ORDER BY COTACOES DESC;

SELECT MES_LEVANTAMENTO, PRD_NOME, PRD_VAR, COT_PAP_ID,
       PAP_QTD, TIPO_APRESENTACAO, UMD_SIGLA,
       QTD_COTACOES, PRECO_MEDIO_MES
FROM MV_PRECOS_MENSAIS
ORDER BY MES_LEVANTAMENTO DESC, PRD_NOME;

SELECT BLT_DATA_LEV, PRD_NOME, PRD_VAR,
       PAP_QTD, TIPO_APRESENTACAO, UMD_SIGLA,
       COT_PRC_MED, PRECO_ANTERIOR, VARIACAO_PERCENTUAL
FROM VW_VARIACAO_BOLETINS
WHERE VARIACAO_PERCENTUAL IS NOT NULL
ORDER BY BLT_DATA_LEV DESC, ABS(VARIACAO_PERCENTUAL) DESC;

SELECT BLT_DATA_LEV, PRD_NOME, PRD_VAR,
       PAP_QTD, TIPO_APRESENTACAO, UMD_SIGLA,
       COT_PRC_MIN, COT_PRC_MAX, AMPLITUDE_PERCENTUAL
FROM VW_DISPERSAO_PRECOS
WHERE AMPLITUDE_PERCENTUAL IS NOT NULL
ORDER BY AMPLITUDE_PERCENTUAL DESC, BLT_DATA_LEV DESC;

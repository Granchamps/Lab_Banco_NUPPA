CREATE MATERIALIZED VIEW MV_PRECOS_MENSAIS
BUILD IMMEDIATE
REFRESH COMPLETE ON DEMAND
AS
SELECT MES_LEVANTAMENTO, COT_PAP_ID, PRD_ID, PRD_NOME, PRD_VAR,
       CAT_NOME, GRP_NOME, PAP_QTD, TIPO_APRESENTACAO, UMD_SIGLA,
       QTD_COTACOES, QTD_COM_PRECO_MEDIO, PRECO_MEDIO_MES,
       MENOR_PRECO_MES, MAIOR_PRECO_MES
FROM VW_PRECOS_MENSAIS;

CREATE MATERIALIZED VIEW MV_PRECOS_ANUAIS
BUILD IMMEDIATE
REFRESH COMPLETE ON DEMAND
AS
SELECT EXTRACT(YEAR FROM BLT_DATA_LEV) AS ANO,
       COT_PAP_ID, PRD_ID, PRD_NOME, PRD_VAR,
       CAT_NOME, GRP_NOME, PAP_QTD, TIPO_APRESENTACAO, UMD_SIGLA,
       COUNT(*) AS QTD_COTACOES,
       COUNT(COT_PRC_MED) AS QTD_COM_PRECO_MEDIO,
       ROUND(AVG(COT_PRC_MED), 2) AS PRECO_MEDIO_ANO,
       MIN(COT_PRC_MIN) AS MENOR_PRECO_ANO,
       MAX(COT_PRC_MAX) AS MAIOR_PRECO_ANO
FROM VW_COTACOES_DETALHADAS
GROUP BY EXTRACT(YEAR FROM BLT_DATA_LEV), COT_PAP_ID,
         PRD_ID, PRD_NOME, PRD_VAR, CAT_NOME, GRP_NOME,
         PAP_QTD, TIPO_APRESENTACAO, UMD_SIGLA;

BEGIN
    DBMS_MVIEW.REFRESH('MV_PRECOS_MENSAIS', 'C');
    DBMS_MVIEW.REFRESH('MV_PRECOS_ANUAIS', 'C');
END;

CREATE TABLE AUDITORIA (
  AUD_ID           NUMBER(12) NOT NULL,
  AUD_EVENTO_ID    NUMBER(12) NOT NULL,
  AUD_REGISTRO_ID  NUMBER(12),
  AUD_TABELA       VARCHAR2(30) NOT NULL,
  AUD_COLUNA       VARCHAR2(30) NOT NULL,
  AUD_VALOR_ANTIGO VARCHAR2(4000),
  AUD_VALOR_NOVO   VARCHAR2(4000),
  AUD_TP_OPERACAO  CHAR(1) NOT NULL,
  AUD_DATA_ENTRADA TIMESTAMP(6) DEFAULT SYSTIMESTAMP NOT NULL,
  AUD_BD_USER      VARCHAR2(128) NOT NULL,
  AUD_SO_USER      VARCHAR2(255),
  CONSTRAINT PK_AUD PRIMARY KEY (AUD_ID),
  CONSTRAINT CK_AUD_OPERACAO CHECK (AUD_TP_OPERACAO IN ('U', 'D'))
);

CREATE INDEX IDX_AUD_EVENTO ON AUDITORIA (AUD_EVENTO_ID);
CREATE INDEX IDX_AUD_REGISTRO ON AUDITORIA (AUD_TABELA, AUD_REGISTRO_ID);
CREATE INDEX IDX_AUD_DATA ON AUDITORIA (AUD_DATA_ENTRADA);

CREATE SEQUENCE SEQ_AUD START WITH 1 INCREMENT BY 1 NOCACHE NOCYCLE;
CREATE SEQUENCE SEQ_AUD_EVENTO START WITH 1 INCREMENT BY 1 NOCACHE NOCYCLE;

CREATE OR REPLACE TRIGGER TG_SEQ_AUD
BEFORE INSERT ON AUDITORIA FOR EACH ROW
BEGIN
  :NEW.AUD_ID := SEQ_AUD.NEXTVAL;
END;
/
SHOW ERRORS TRIGGER TG_SEQ_AUD;

CREATE OR REPLACE PROCEDURE PR_INSERE_AUDITORIA (
  P_EVENTO_ID     IN NUMBER,
  P_REGISTRO_ID   IN NUMBER,
  P_TABELA        IN VARCHAR2,
  P_COLUNA        IN VARCHAR2,
  P_VALOR_ANTIGO  IN VARCHAR2,
  P_VALOR_NOVO    IN VARCHAR2,
  P_TP_OPERACAO   IN CHAR,
  P_DATA_ENTRADA  IN TIMESTAMP,
  P_BD_USER       IN VARCHAR2,
  P_SO_USER       IN VARCHAR2
) IS
BEGIN
  IF P_TP_OPERACAO = 'U' THEN
    IF P_VALOR_ANTIGO = P_VALOR_NOVO
       OR (P_VALOR_ANTIGO IS NULL AND P_VALOR_NOVO IS NULL) THEN
       RETURN;
    END IF;
  END IF;

  INSERT INTO AUDITORIA (
    AUD_EVENTO_ID, AUD_REGISTRO_ID, AUD_TABELA, AUD_COLUNA,
    AUD_VALOR_ANTIGO, AUD_VALOR_NOVO, AUD_TP_OPERACAO,
    AUD_DATA_ENTRADA, AUD_BD_USER, AUD_SO_USER
  ) VALUES (
    P_EVENTO_ID, P_REGISTRO_ID, P_TABELA, P_COLUNA,
    P_VALOR_ANTIGO, P_VALOR_NOVO, P_TP_OPERACAO,
    P_DATA_ENTRADA, P_BD_USER, P_SO_USER
  );
END;
/
SHOW ERRORS PROCEDURE PR_INSERE_AUDITORIA;

GRANT EXECUTE ON PR_INSERE_AUDITORIA TO NUPPA;
GRANT SELECT ON SEQ_AUD_EVENTO TO NUPPA;